#!/usr/bin/env bash
set -euo pipefail
: "${AUTORLBENCH_WORKSPACE:?}" "${AUTORLBENCH_VERIFIER:?}" "${AUTORLBENCH_RESULTS:?}"
export W=$AUTORLBENCH_WORKSPACE
export HOME="$AUTORLBENCH_RESULTS/home" TMPDIR="$AUTORLBENCH_RESULTS/tmp"
mkdir -p "$HOME" "$TMPDIR"
variant=$(cat "$W/variant.txt")
export PYTHONPATH="$W/src/$variant:$W/scripts:$AUTORLBENCH_VERIFIER/tests"
export PYTHONNOUSERSITE=1 PYTHONDONTWRITEBYTECODE=1
export HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 TRAINING_RUNTIME_HOOK=1
exec "${AUTORLBENCH_PYTHON:-/usr/bin/python3.12}" "$AUTORLBENCH_VERIFIER/tests/verify.py"
