#!/usr/bin/env bash
# slime_critic_value_head_random_init: what to prepare before training.
#
# Runs in a separate prepare-stage container: root, the `slime-v0.3.2` image,
# **the only stage with network**, and $AUTORLBENCH_WORKSPACE, $AUTORLBENCH_MODELS,
# and $AUTORLBENCH_DATASETS are all writable. The assets are immutable inputs to
# every later stage: the agent and the verifier see the same bytes this script
# stages, so anything an agent could change here would change the task itself.
set -euo pipefail
: "${AUTORLBENCH_WORKSPACE:?}"

# --- Weights ------------------------------------------------------------------
# The base policy; run.sh's MODEL_DIR default reads workspace/Qwen3-1.7B.
python3 "$AUTORLBENCH_ENVIRONMENT/fetch_hf.py" \
    --repo Qwen/Qwen3-1.7B \
    --dest "$AUTORLBENCH_WORKSPACE/Qwen3-1.7B"

# --- Endless Terminals prompt set (the prebuilt ET_DATA_ROOT payload) ---------
# The original task_* tree is NOT downloaded from HF, and the agent stage does
# not run et.build_dataset's transpile+validate pass (~40 min of CPU). Reasons:
# (1) downloading the raw obiwan96/endless-terminals dataset is unreliable
# through the whitelist egress; (2) the validation result (2492 candidates ->
# 1489 admitted) is deterministic and reproducible under the declared image,
# so there is no need to recompute it every run.
#
# Instead the *output* of build_dataset ships with the task: unpacking
# environment/et_prompts.tar.gz yields the complete ET_DATA_ROOT payload --
#   endless_terminals.jsonl / _{train,val,test}.jsonl   (1489 admitted + the
#                                                       fixed split)
#   splits.json / validation_report.json
#   tasks/<id>/{setup.sh, instruction.md, test_final_state.py, test_initial_state.py}
# setup.sh is transpiled from the original Dockerfile by the repo's own
# et.build_dataset.transpile(), and the split is generated by et.make_splits
# with a fixed seed (byte-checked against the submitter's splits.json).
# run.sh sees ET_DATA_ROOT already populated and skips the download / transpile
# / validate path, so ET_SRC is never read.
mkdir -p "$AUTORLBENCH_WORKSPACE/et_prompts"
tar -xzf "$AUTORLBENCH_ENVIRONMENT/et_prompts.tar.gz" -C "$AUTORLBENCH_WORKSPACE/et_prompts"
